-- Whole database schema of the Contractor app.
-- Update this file in the same change that needs a new table or column,
-- then apply the change to the dev database by hand (see specs/tech-stack.md).
-- Tests rebuild their database from this file on every run.

CREATE TABLE branches (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    city VARCHAR(255)
);

CREATE TABLE clients (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type           VARCHAR(20)  NOT NULL CHECK (type IN ('COMPANY', 'INDIVIDUAL')),
    name           VARCHAR(255) NOT NULL,
    contact_person VARCHAR(255),
    phone          VARCHAR(255),
    email          VARCHAR(255),
    -- Billing address, printed on the invoice. Work sites are in locations.
    address        VARCHAR(255)
);

-- Work sites of a client. Deleted together with the client (JPA cascade on Client.locations).
CREATE TABLE locations (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT       NOT NULL REFERENCES clients (id),
    name      VARCHAR(255),
    address   VARCHAR(255) NOT NULL,
    city      VARCHAR(255) NOT NULL
);

-- Employees for now. client_id comes with the clients table (roadmap step 6).
CREATE TABLE users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     VARCHAR(255) NOT NULL UNIQUE,
    password     VARCHAR(255) NOT NULL,
    role         VARCHAR(20)  NOT NULL CHECK (role IN ('ADMIN', 'OFFICE', 'SERVICER', 'CLIENT')),
    display_name VARCHAR(255) NOT NULL,
    branch_id    BIGINT REFERENCES branches (id),
    -- false = deactivated: can't log in, rows that point to the user stay as they are
    active       BOOLEAN      NOT NULL DEFAULT TRUE
);
