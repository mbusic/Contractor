    ('PENDING',     'DRAFT'),    ('PENDING',     'IN_PROGRESS'), ('PENDING',     'RESOLVED'),    ('PENDING',     'CANCELLED'),
    ('IN_PROGRESS', 'DRAFT'),    ('IN_PROGRESS', 'PENDING'),     ('IN_PROGRESS', 'RESOLVED'),    ('IN_PROGRESS', 'CANCELLED'),
    ('RESOLVED',    'DRAFT'),    ('RESOLVED',    'PENDING'),     ('RESOLVED',    'IN_PROGRESS'), ('RESOLVED',    'CANCELLED'),
    ('CANCELLED',   'DRAFT'),    ('CANCELLED',   'PENDING'),     ('CANCELLED',   'IN_PROGRESS'), ('CANCELLED',   'RESOLVED');

-- Per-year counter for order numbers (NNN/YY). OrderNumberGenerator increases it with one upsert.
CREATE TABLE order_sequences (
    seq_year      INTEGER PRIMARY KEY,
    last_sequence INTEGER NOT NULL
);

-- "order" is a reserved word in SQL, so the table is "orders".
-- Client, location and order number can be empty while the order is a DRAFT (or a cancelled draft).
CREATE TABLE orders (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number                VARCHAR(20) UNIQUE,
    branch_id                   BIGINT REFERENCES branches (id),
    client_id                   BIGINT REFERENCES clients (id),
    location_id                 BIGINT REFERENCES locations (id),
    contact_person              VARCHAR(255),
    phone                       VARCHAR(255),
    email                       VARCHAR(255),
    description                 TEXT,
    urgency                     VARCHAR(20) CHECK (urgency IN ('SAME_DAY', 'ONE_DAY', 'ONE_WEEK', 'ONE_MONTH', 'SIX_MONTHS')),
    status                      VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT', 'PENDING', 'IN_PROGRESS', 'RESOLVED', 'CANCELLED')),
    assigned_servicer_id        BIGINT REFERENCES users (id),
    estimated_km                INTEGER,
    estimated_work_hours        NUMERIC(6, 2),
    estimated_number_of_workers INTEGER,
    estimated_material_cost     NUMERIC(10, 2),
    actual_km                   INTEGER,
    actual_work_hours           NUMERIC(6, 2),
    actual_number_of_workers    INTEGER,
    actual_material_cost        NUMERIC(10, 2),
    created_at                  TIMESTAMPTZ NOT NULL,
    updated_at                  TIMESTAMPTZ NOT NULL
);
